#!/usr/bin/env python3
"""Export the native dated-sky wrapper and its exact source/artifact receipt.

This is the same producer used by oi-source-install.sh, without a Rust/C build.
Provider resources retain their native QL ownership and original bytes.
"""
import argparse
import base64
import gzip
import hashlib
import io
import json
import os
from pathlib import Path
import shlex
import shutil
import subprocess
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = (
    'providers/sky/kerykeion_snapshot.py',
    'providers/sky/requirements.txt',
    'vendor/epi-kernel/reference/include/m2.h',
    'fixtures/kernel/m2-retained-c-v1.json',
)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def source_record(member, data=None):
    if data is None:
        data = (ROOT / member).read_bytes()
    return {'path': member, 'size_bytes': len(data), 'sha256': sha256(data)}


def archive(resources):
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode='w', format=tarfile.USTAR_FORMAT) as bundle:
        for member in RESOURCES:
            data = resources[member]
            record = tarfile.TarInfo(member)
            record.size = len(data)
            record.mode = 0o644
            bundle.addfile(record, io.BytesIO(data))
    return base64.b64encode(gzip.compress(buffer.getvalue(), mtime=0)).decode('ascii')


def command(payload, installed_uv):
    digest = sha256(payload.encode('ascii'))[:16]
    return ('#!/bin/sh\n'
            '# Generated by scripts/export-sky.py; payload ' + digest + '\n'
            'set -eu\n'
            'payload=' + payload + '\n'
            'dir="${XDG_CACHE_HOME:-$HOME/.cache}/ql-sky/' + digest + '"\n'
            'installed_uv=' + shlex.quote(installed_uv) + '\n' + '''
if [ ! -f "$dir/providers/sky/kerykeion_snapshot.py" ]; then
  tmp="$dir.tmp.$$"; mkdir -p "$tmp"
  printf %s "$payload" | base64 -d | gzip -dc | tar -xf - -C "$tmp"
  mv "$tmp" "$dir" 2>/dev/null || rm -rf "$tmp"
fi
# An explicit host-qualified interpreter preserves its lexical venv path.
# Invalid explicit bindings never fall through to a different interpreter.
if [ "${QL_SKY_PYTHON+x}" = x ]; then
  case "$QL_SKY_PYTHON" in
    /*) ;;
    *) echo '{"schema":"ql.sky-error/v1","error":"QL_SKY_PYTHON must name an absolute executable file","snapshot":null}' >&2; exit 2 ;;
  esac
  [ -f "$QL_SKY_PYTHON" ] && [ -x "$QL_SKY_PYTHON" ] || {
    echo '{"schema":"ql.sky-error/v1","error":"QL_SKY_PYTHON is not an executable file","snapshot":null}' >&2; exit 2;
  }
  exec "$QL_SKY_PYTHON" "$dir/providers/sky/kerykeion_snapshot.py" "$@"
fi
uv=$(command -v uv || true); [ -n "$uv" ] || uv=$installed_uv
[ -n "$uv" ] && [ -x "$uv" ] || { echo '{"schema":"ql.sky-error/v1","error":"uv is required for the dated-sky provider","snapshot":null}' >&2; exit 2; }
exec "$uv" run --quiet --no-project --python-preference only-managed --python 3.13 \\
  --with-requirements "$dir/providers/sky/requirements.txt" \\
  python "$dir/providers/sky/kerykeion_snapshot.py" "$@"
''').encode('utf-8')


def git(*args):
    return subprocess.check_output(['git', '-C', str(ROOT), *args], text=True).strip()


def atomic_write(path, data, mode=0o644):
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix='.' + path.name + '-', dir=path.parent)
    try:
        with os.fdopen(descriptor, 'wb') as stream:
            stream.write(data)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--receipt', type=Path)
    parser.add_argument('--installed-uv', default=shutil.which('uv') or '',
                        help='Default uv fallback captured at source install; an empty value omits it')
    args = parser.parse_args()
    resources = {member: (ROOT / member).read_bytes() for member in RESOURCES}
    payload = archive(resources)
    data = command(payload, args.installed_uv)
    if args.receipt and args.receipt.resolve() == args.output.resolve():
        parser.error('--receipt and --output must be distinct paths')
    inputs = [source_record(member, resources.get(member)) for member in ('scripts/export-sky.py', 'scripts/oi-source-install.sh', *RESOURCES)]
    receipt = {
        'schema': 'ql.sky-command-export/v1',
        'source_root': str(ROOT),
        'source_revision': git('rev-parse', 'HEAD'),
        'source_git_tree': git('rev-parse', 'HEAD^{tree}'),
        'source_dirty': bool(git('status', '--porcelain', '--untracked-files=normal')),
        'source_inputs': inputs,
        'source_input_sha256': sha256(json.dumps(inputs, sort_keys=True, separators=(',', ':')).encode()),
        'resources': [source_record(member, resources[member]) for member in RESOURCES],
        'payload_sha256': sha256(payload.encode('ascii')),
        'installed_uv_fallback': args.installed_uv or None,
        'artifact': {'path': str(args.output.resolve()), 'kind': 'shell-script', 'interpreter': '/bin/sh',
                     'size_bytes': len(data), 'sha256': sha256(data)},
    }
    atomic_write(args.output, data, 0o755)
    if args.receipt:
        atomic_write(args.receipt, (json.dumps(receipt, indent=2, sort_keys=True) + '\n').encode())
    print(json.dumps({'artifact': receipt['artifact'], 'source_dirty': receipt['source_dirty']}))


if __name__ == '__main__':
    main()
